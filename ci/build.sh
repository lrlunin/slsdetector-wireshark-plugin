#!/usr/bin/env bash
#
# Build the SLS Wireshark plugin for one Wireshark release line.
#
#   ci/build.sh <ws-line> <platform> [out-dir]
#
#   ws-line   2.6 | 3.6 | 4.6
#   platform  linux | windows | macos
#
# Only Wireshark's *headers* are needed (fetched from the GitHub mirror),
# plus GLib headers from the system / MSYS2 / Homebrew.
#   linux   : symbols resolve at load time from the running Wireshark
#   macos   : same, via -undefined dynamic_lookup (universal x86_64+arm64)
#   windows : an import library for libwireshark.dll is generated from the
#             symbols the plugin actually uses (MinGW/MSYS2 UCRT64)
#
set -euo pipefail

WS_LINE="${1:?usage: build.sh <2.6|3.6|4.6> <linux|windows|macos> [out-dir]}"
PLATFORM="${2:?usage: build.sh <2.6|3.6|4.6> <linux|windows|macos> [out-dir]}"
OUT_DIR="${3:-dist}"

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SRC="$ROOT/packet-sls.c"
WORK="$ROOT/build/$WS_LINE-$PLATFORM"
CC="${CC:-cc}"

# Header source per release line (any patch release of a line is ABI compatible)
case "$WS_LINE" in
  2.6) WS_TAG="wireshark-2.6.20" ;;
  3.6) WS_TAG="wireshark-3.6.24" ;;
  4.6) WS_TAG="v4.6.9" ;;
  *) echo "unsupported Wireshark line: $WS_LINE" >&2; exit 1 ;;
esac
WS_TAG="${WS_TAG_OVERRIDE:-$WS_TAG}"
MAJOR="${WS_LINE%%.*}"
MINOR="${WS_LINE##*.}"

mkdir -p "$WORK" "$OUT_DIR"
OUT_DIR="$(cd "$OUT_DIR" && pwd)"

# ---------------------------------------------------------------- headers
WS_SRC="$WORK/wireshark"
if [ ! -f "$WS_SRC/epan/packet.h" ]; then
  echo ">> fetching Wireshark headers ($WS_TAG)"
  mkdir -p "$WS_SRC"
  # only headers are needed (also avoids symlink/filename trouble on Windows)
  if tar --version 2>/dev/null | grep -q 'GNU tar'; then
    TAR_FILTER=(--wildcards '*.h')
  else
    TAR_FILTER=('*.h')            # bsdtar (macOS)
  fi
  curl -fsSL "https://codeload.github.com/wireshark/wireshark/tar.gz/refs/tags/$WS_TAG" \
    | tar xzf - -C "$WS_SRC" --strip-components=1 "${TAR_FILTER[@]}"
  test -f "$WS_SRC/epan/packet.h" || { echo "header download failed" >&2; exit 1; }
fi

# ws_version.h is generated by CMake in 3.x+; provide it ourselves
GEN="$WORK/gen"
mkdir -p "$GEN"
if [ "$MAJOR" -ge 3 ]; then
  cat > "$GEN/ws_version.h" <<EOF
#ifndef __WS_VERSION_H__
#define __WS_VERSION_H__
#define WIRESHARK_VERSION_MAJOR $MAJOR
#define WIRESHARK_VERSION_MINOR $MINOR
#define WIRESHARK_VERSION_MICRO 0
#endif
EOF
fi

INCLUDES=(-I"$GEN" -I"$WS_SRC" -I"$WS_SRC/include")
GLIB_CFLAGS="${GLIB_CFLAGS:-$(${PKG_CONFIG:-pkg-config} --cflags glib-2.0)}"
PLUGIN_VERSION="${PLUGIN_VERSION:-1.0.0}"
CFLAGS=(-std=gnu11 -O2 -Wall -fvisibility=hidden -DSLS_PLUGIN_VERSION=\"$PLUGIN_VERSION\")

# ---------------------------------------------------------------- compile
case "$PLATFORM" in
  linux)
    ARCH="$(uname -m)"
    PKG="sls-wireshark-$WS_LINE-linux-$ARCH"
    PLUGIN="sls.so"
    PLUGIN_SUBDIR="$WS_LINE/epan"
    "$CC" "${CFLAGS[@]}" -fPIC -shared -s -fno-stack-protector \
      "${INCLUDES[@]}" $GLIB_CFLAGS "$SRC" -o "$WORK/$PLUGIN"
    ;;

  macos)
    PKG="sls-wireshark-$WS_LINE-macos-universal"
    PLUGIN="sls.so"
    # Wireshark.app uses "X-Y" (no dot) for plugin folders since 3.x
    if [ "$MAJOR" -ge 3 ]; then PLUGIN_SUBDIR="$MAJOR-$MINOR/epan"; else PLUGIN_SUBDIR="$WS_LINE/epan"; fi
    "$CC" "${CFLAGS[@]}" -fPIC -bundle -undefined dynamic_lookup \
      -arch x86_64 -arch arm64 -mmacosx-version-min=10.13 \
      "${INCLUDES[@]}" $GLIB_CFLAGS "$SRC" -o "$WORK/$PLUGIN"
    ;;

  windows)
    PKG="sls-wireshark-$WS_LINE-windows-x64"
    PLUGIN="sls.dll"
    PLUGIN_SUBDIR="$WS_LINE/epan"
    OBJ="$WORK/packet-sls.o"
    "$CC" "${CFLAGS[@]}" -c "${INCLUDES[@]}" $GLIB_CFLAGS "$SRC" -o "$OBJ"

    # Every dllimport'ed symbol must come from libwireshark.dll; refuse
    # anything else (e.g. GLib or libwsutil) instead of producing a DLL
    # that fails to load.
    NM="${NM:-nm}"
    "$NM" -u "$OBJ" | awk '{print $NF}' | grep '^__imp_' | sed 's/^__imp_//' | sort -u > "$WORK/imports.txt"
    # (wmem_epan_scope lives in epan, i.e. libwireshark, on every line)
    if grep -E '^(g_|ws_|wmem_|try_val_to_str|val_to_str)' "$WORK/imports.txt" | grep -vx 'wmem_epan_scope'; then
      echo "error: imports above are not in libwireshark.dll" >&2; exit 1
    fi
    { echo "LIBRARY libwireshark.dll"; echo "EXPORTS"; sed 's/^/    /' "$WORK/imports.txt"; } > "$WORK/libwireshark.def"
    DLLTOOL="${DLLTOOL:-dlltool}"
    "$DLLTOOL" -d "$WORK/libwireshark.def" -l "$WORK/libwireshark.dll.a"
    "$CC" -shared -s -static-libgcc "$OBJ" "$WORK/libwireshark.dll.a" -o "$WORK/$PLUGIN"
    ;;

  *) echo "unsupported platform: $PLATFORM" >&2; exit 1 ;;
esac

# ---------------------------------------------------------------- package
STAGE="$WORK/stage/$PKG"
rm -rf "$WORK/stage"
mkdir -p "$STAGE/plugins/$PLUGIN_SUBDIR"
cp "$WORK/$PLUGIN" "$STAGE/plugins/$PLUGIN_SUBDIR/"
cp "$ROOT/README.md" "$STAGE/" 2>/dev/null || true
cat > "$STAGE/INSTALL.txt" <<EOF
SLS detector dissector for Wireshark $WS_LINE ($PLATFORM)

Copy plugins/$PLUGIN_SUBDIR/$PLUGIN into your personal plugin folder:

  Linux  : ~/.local/lib/wireshark/plugins/$PLUGIN_SUBDIR/
  macOS  : ~/.local/lib/wireshark/plugins/$PLUGIN_SUBDIR/
  Windows: %APPDATA%\\Wireshark\\plugins\\${PLUGIN_SUBDIR//\//\\}\\

(The exact base folder is listed under Help > About Wireshark > Folders.)
macOS: if the file was downloaded with a browser, run
  xattr -d com.apple.quarantine sls.so
Restart Wireshark; the plugin appears under Help > About Wireshark > Plugins.
EOF

(
  cd "$WORK/stage"
  rm -f "$OUT_DIR/$PKG.zip"
  zip -qr "$OUT_DIR/$PKG.zip" "$PKG"
)
echo ">> built $OUT_DIR/$PKG.zip"
